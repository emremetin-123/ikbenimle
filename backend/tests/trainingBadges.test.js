const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const express = require('express');
const cookieParser = require('cookie-parser');
process.env.DB_TYPE = 'sqlite';
process.env.NODE_ENV = 'test';
process.env.SEED_DEFAULT_USERS = 'false';
const setupDb = require('../database');
const { runMigrations, MIGRATIONS } = require('../migrations');
const { setAuthDatabase, authenticateToken } = require('../middleware/auth');
const { authorizeUpload } = require('../middleware/uploadAccess');
const createRoutes = require('../modules/training/adminTrainingMutationRoutes');
const { createEmployeeLearningRepository } = require('../modules/employee/employeeLearningRepository');
const { createDirectoryRepository } = require('../modules/directory/directoryRepository');

test('yüklenen rozet zorunluluğu, sürümler, yetkiler ve tamamlanan eğitim görselleri korunur', async t => {
    const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'training-badges-'));
    process.env.SQLITE_FILENAME = path.join(tempDir, 'test.sqlite');
    const db = await setupDb();
    await runMigrations(db);
    setAuthDatabase(db);
    const files = new Set();
    const sessions = [];
    for (const [employeeId, role] of [['badge-admin', 'admin'], ['badge-owner', 'employee'], ['badge-viewer', 'employee']]) {
        const user = await db.run('INSERT INTO users (employee_id, name, role, status, permissions) VALUES (?, ?, ?, ?, ?)', [employeeId, employeeId, role, 'active', '[]']);
        const token = crypto.randomUUID();
        const csrf = crypto.randomUUID();
        const expiry = new Date(Date.now() + 3_600_000).toISOString();
        const hash = value => crypto.createHash('sha256').update(value).digest('hex');
        await db.run('INSERT INTO auth_sessions (token_hash, csrf_hash, user_id, idle_expires_at, absolute_expires_at) VALUES (?, ?, ?, ?, ?)', [hash(token), hash(csrf), user.lastID, expiry, expiry]);
        sessions.push({ id: user.lastID, headers: { Cookie: `ikbenimle_session=${token}; ikbenimle_csrf=${csrf}`, 'X-CSRF-Token': csrf } });
    }
    const [admin, owner, viewer] = sessions;
    const app = express();
    app.use(cookieParser());
    app.use('/api/admin', createRoutes(db));
    app.use('/uploads', authenticateToken, authorizeUpload(db), (_req, res) => res.sendStatus(204));
    app.use((error, _req, res, _next) => res.status(error.status || 400).json({ error: error.message }));
    const server = app.listen(0);
    await new Promise(resolve => server.once('listening', resolve));
    t.after(async () => {
        server.closeAllConnections();
        await new Promise(resolve => server.close(resolve));
        await db.close();
        for (const url of files) fs.rmSync(path.join(__dirname, '..', 'uploads', 'videos', path.basename(url)), { force: true });
        fs.rmSync(tempDir, { recursive: true, force: true });
    });
    const base = `http://127.0.0.1:${server.address().port}`;
    const request = (method, endpoint, body, session = admin) => fetch(`${base}/api/admin${endpoint}`, { method, headers: session.headers, body });
    const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
    const form = (image = false) => {
        const data = new FormData();
        data.set('title', 'Özel rozetli eğitim');
        data.set('awards_badge', 'true');
        data.set('requires_full_watch', 'false');
        data.set('requires_quiz', 'false');
        data.set('modules', JSON.stringify([{ title: 'Modül', contents: [{ title: 'İçerik', content_type: 'pdf', url: 'https://example.test/lesson.pdf' }] }]));
        if (image) data.set('badge_image_file', new Blob([png], { type: 'image/png' }), 'badge.png');
        return data;
    };
    assert.equal((await request('POST', '/video', form(), owner)).status, 403);
    assert.equal((await request('POST', '/video', form())).status, 400);
    const spoofed = form();
    spoofed.set('badge_image_url', '/uploads/videos/someone-elses.png');
    assert.equal((await request('POST', '/video', spoofed)).status, 400);
    const invalid = form();
    invalid.set('badge_image_file', new Blob(['not a PNG, despite the MIME'], { type: 'image/png' }), 'badge.png');
    assert.equal((await request('POST', '/video', invalid)).status, 400);
    const oversized = form();
    const largeImage = Buffer.alloc(10 * 1024 * 1024 + 1);
    png.copy(largeImage);
    oversized.set('badge_image_file', new Blob([largeImage], { type: 'image/png' }), 'large.png');
    assert.equal((await request('POST', '/video', oversized)).status, 400);
    const duplicate = form(true);
    duplicate.append('badge_image_file', new Blob([png], { type: 'image/png' }), 'second.png');
    assert.equal((await request('POST', '/video', duplicate)).status, 400);
    const created = await request('POST', '/video', form(true));
    assert.equal(created.status, 200, await created.clone().text());
    const { videoId } = await created.json();
    let video = await db.get('SELECT * FROM videos WHERE id = ?', [videoId]);
    files.add(video.badge_image_url);
    assert.match(video.badge_image_url, /^\/uploads\/videos\/videos-[\w-]+\.png$/);
    assert.deepEqual(fs.readFileSync(path.join(__dirname, '..', video.badge_image_url)), png);
    assert.equal((await fetch(`${base}${video.badge_image_url}`, { headers: viewer.headers })).status, 403);
    assert.equal((await fetch(`${base}${video.badge_image_url}?badgeSize=256`, { headers: viewer.headers })).status, 403);
    const update = form();
    update.set('badge_image_url', '/uploads/videos/ignored.png');
    assert.equal((await request('PUT', `/video/${videoId}`, update)).status, 200);
    assert.equal((await db.get('SELECT badge_image_url FROM videos WHERE id = ?', [videoId])).badge_image_url, video.badge_image_url);
    const remove = form();
    remove.set('remove_badge_image', 'true');
    assert.equal((await request('PUT', `/video/${videoId}`, remove)).status, 400);
    await db.run("INSERT INTO assignments (user_id, video_id, status, completed_at) VALUES (?, ?, 'completed', CURRENT_TIMESTAMP)", [owner.id, videoId]);
    const version = await request('PUT', `/video/${videoId}`, form(true));
    assert.equal(version.status, 200, await version.clone().text());
    const versionInfo = await version.json();
    assert.equal(versionInfo.newVersion, true);
    const next = await db.get('SELECT badge_image_url FROM videos WHERE id = ?', [versionInfo.videoId]);
    files.add(next.badge_image_url);
    assert.notEqual(next.badge_image_url, video.badge_image_url);
    assert.equal((await db.get('SELECT badge_image_url FROM videos WHERE id = ?', [videoId])).badge_image_url, video.badge_image_url);
    const badges = await createDirectoryRepository(db).listBadges(owner.id);
    assert.equal(badges[0].badge_image_url, video.badge_image_url);
    const list = await createEmployeeLearningRepository(db).listTrainings(owner.id, { status: 'completed', badge: 'awarded', sort: 'completed_at', order: 'desc' }, { startRow: 1, endRow: 12 });
    assert.equal(list.items[0].badge_image_url, video.badge_image_url);
    assert.equal((await fetch(`${base}${video.badge_image_url}`, { headers: viewer.headers })).status, 204);
    assert.equal((await fetch(`${base}${video.badge_image_url}?badgeSize=256`, { headers: viewer.headers })).status, 204);
    assert.equal((await fetch(`${base}${video.badge_image_url}`)).status, 401);
    const disable = form();
    disable.set('awards_badge', 'false');
    disable.set('remove_badge_image', 'true');
    assert.equal((await request('PUT', `/video/${versionInfo.videoId}`, disable)).status, 200);
    assert.equal((await db.get('SELECT badge_image_url FROM videos WHERE id = ?', [versionInfo.videoId])).badge_image_url, '');
    const migration = MIGRATIONS.find(item => item.version === '023_training_badge_images');
    await migration.down(db);
    assert.equal((await db.all('PRAGMA table_info(videos)')).some(column => column.name === 'badge_image_url'), false);
    await migration.up(db);
    assert.equal((await db.all('PRAGMA table_info(videos)')).some(column => column.name === 'badge_image_url'), true);
});

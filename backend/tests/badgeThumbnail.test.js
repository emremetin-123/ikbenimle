const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { randomBytes } = require('node:crypto');
const express = require('express');
const sharp = require('sharp');
process.env.DB_TYPE = 'sqlite';
process.env.NODE_ENV = 'test';
process.env.SEED_DEFAULT_USERS = 'false';
const setupDb = require('../database');
const { runMigrations } = require('../migrations');
const { authorizeUpload } = require('../middleware/uploadAccess');
const { badgeThumbnail } = require('../middleware/badgeThumbnail');
const { privateFileHandler } = require('../middleware/privateFiles');

test('badge previews reduce bytes without cropping, preserve originals and recheck access even for cached images', async t => {
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'badge-thumbnail-'));
    process.env.SQLITE_FILENAME = path.join(root, 'test.sqlite');
    const db = await setupDb(); await runMigrations(db);
    await fs.mkdir(path.join(root, 'videos'));
    const filename = path.join(root, 'videos', 'badge.png');
    await sharp(randomBytes(1200 * 600 * 4), { raw: { width: 1200, height: 600, channels: 4 } }).png().toFile(filename);
    const original = await fs.readFile(filename);
    await fs.writeFile(path.join(root, 'videos', 'lesson.png'), original);
    const users = {};
    for (const name of ['viewer', 'owner', 'admin']) {
        const user = await db.run('INSERT INTO users (employee_id, name, role, status) VALUES (?, ?, ?, ?)', [name, name, name === 'admin' ? 'admin' : 'employee', 'active']);
        users[name] = { id: user.lastID, role: name === 'admin' ? 'admin' : 'employee', permissions: [] };
    }
    const video = await db.run('INSERT INTO videos (title, url, badge_image_url, awards_badge) VALUES (?, ?, ?, ?)', ['Badge training', '/uploads/videos/lesson.png', '/uploads/videos/badge.png', 1]);
    await db.run("INSERT INTO assignments (user_id, video_id, status) VALUES (?, ?, 'completed')", [users.owner.id, video.lastID]);
    const app = express();
    app.use('/uploads', (req, res, next) => {
        req.user = users[req.headers['x-test-session']];
        return req.user ? next() : res.sendStatus(401);
    }, authorizeUpload(db), badgeThumbnail(db, root), privateFileHandler(root));
    app.use((error, _req, res, _next) => res.sendStatus(error.status || 500));
    const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
    t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await db.close(); await fs.rm(root, { recursive: true, force: true }); });
    const base = `http://127.0.0.1:${server.address().port}/uploads/videos/`;
    const headers = { 'x-test-session': 'viewer' };
    const url = base + 'badge.png?badgeSize=256';
    const response = await fetch(url, { headers });
    const preview = Buffer.from(await response.arrayBuffer());
    assert.equal(response.status, 200);
    assert.match(response.headers.get('content-type'), /image\/webp/);
    assert.equal(response.headers.get('cache-control'), 'private, no-cache');
    assert.ok(preview.length < original.length / 10);
    const meta = await sharp(preview).metadata();
    assert.equal(meta.width, 256); assert.equal(meta.height, 128); assert.equal(meta.hasAlpha, true);
    t.diagnostic(`Badge bytes: ${original.length} original -> ${preview.length} preview`);
    const etag = response.headers.get('etag');
    assert.ok(etag);
    assert.equal((await fetch(url, { headers: { ...headers, 'If-None-Match': etag }, cache: 'force-cache' })).status, 304);
    assert.equal((await fetch(url, { headers: { 'If-None-Match': etag } })).status, 401);
    const head = await fetch(url, { headers, method: 'HEAD' });
    assert.equal(head.status, 200); assert.equal((await head.arrayBuffer()).byteLength, 0);
    const normal = await fetch(base + 'badge.png', { headers });
    assert.deepEqual(Buffer.from(await normal.arrayBuffer()), original);
    assert.equal(normal.headers.get('cache-control'), 'private, no-store');
    assert.deepEqual(await fs.readFile(filename), original);
    const other = await fetch(base + 'lesson.png?badgeSize=256', { headers: { 'x-test-session': 'admin' } });
    assert.match(other.headers.get('content-type'), /image\/png/);
    assert.deepEqual(Buffer.from(await other.arrayBuffer()), original);
    assert.equal((await fetch(base + 'lesson.png?badgeSize=256', { headers })).status, 403);
    assert.equal((await fetch(base + 'badge.png?badgeSize=9999', { headers })).status, 400);
    assert.equal((await fetch(base + 'badge.png?badgeSize=256&badgeSize=320', { headers })).status, 400);
    await db.run("UPDATE assignments SET status = 'cancelled' WHERE video_id = ?", [video.lastID]);
    assert.equal((await fetch(url, { headers: { ...headers, 'If-None-Match': etag } })).status, 403);
    await db.run("UPDATE assignments SET status = 'completed' WHERE video_id = ?", [video.lastID]);
    await sharp({ create: { width: 200, height: 400, channels: 4, background: '#ff000080' } }).png().toFile(filename);
    const changed = await fetch(url, { headers: { ...headers, 'If-None-Match': etag } });
    assert.equal(changed.status, 200); assert.notEqual(changed.headers.get('etag'), etag);
    const changedMeta = await sharp(Buffer.from(await changed.arrayBuffer())).metadata();
    assert.equal(changedMeta.width, 128); assert.equal(changedMeta.height, 256);
    await fs.writeFile(filename, 'unsupported image');
    const unsupported = await fetch(url, { headers });
    assert.equal(unsupported.status, 200); assert.equal(await unsupported.text(), 'unsupported image');
    await fs.unlink(filename);
    assert.equal((await fetch(url, { headers })).status, 404);
});
